ORDER = ["three", "three_bold", "four", "four_bold"]   # tiles $170, $172, $174, $176


def tile_bytes(rows):
    """8 rows of 8 color indices -> 32 bytes of SNES 4bpp planar data."""
    out = bytearray(32)
    for y, row in enumerate(rows):
        for x, c in enumerate(row):
            for p in range(4):
                if c >> p & 1:
                    out[(p // 2) * 16 + y * 2 + (p & 1)] |= 0x80 >> x
    return out


def main():
    top, bottom = bytearray(), bytearray()
    for name in ORDER:
        lines = [l for l in GLYPHS[name].strip("\n").split("\n")]
        assert len(lines) == 16 and all(len(l) == 16 for l in lines), name
        px = [[0 if c == "." else int(c, 16) for c in l] for l in lines]
        for half, dest in ((0, top), (8, bottom)):
            for col in (0, 8):
                dest += tile_bytes([r[col:col + 8] for r in px[half:half + 8]])
    with open(sys.argv[1], "w") as f:
        f.write("; Generated by scripts/gen_select_glyphs.py - do not edit.\n")
        for label, data in (("SelGlyphTop", top), ("SelGlyphBottom", bottom)):
            f.write(f"{label}:\n")
            for i in range(0, len(data), 16):
                f.write("    db " + ", ".join(f"${b:02X}" for b in data[i:i + 16]) + "\n")


if __name__ == "__main__":
    main()
